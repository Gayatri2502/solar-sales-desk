import {it,expect,vi} from 'vitest';
import {firebaseFixture,tenant} from '../helpers/firebase';
import {FirebaseBridge,firebaseMutate} from '../../server/firebase/bridge';
import {runJob,handleProviderWebhook} from '../../server/integrations/service';
import {reduce,mockExtract} from '../../src/domain';

it('voice dispatch and authenticated callback lead to a reviewed quote and one approved order, never an automatic sale',async()=>{
 const {store,ctx,sales,docs}=firebaseFixture();
 let s=docs.get('/businesses/'+tenant)!.value;
 s.leads=[];s.quotes=[];s.orders=[];s.communicationJobs=[];s.callRecords=[];
 s.customers[0].phone='+919999999999';s.settings.taxBps=0;s.settings.deliveryTaxBps=0;
 const before=new Date(Date.now()-120000).toISOString();
 const due=new Date(Date.now()-60000).toISOString();
 s=reduce(s,{type:'lead.capture',lead:{customerId:s.customers[0].id,source:'Website form',sourceReference:'voice-flow-fixture',whatsapp:'',notes:''}},ctx,before);
 const leadId=s.leads![0].id;
 s=reduce(s,{type:'lead.qualify',id:leadId,response:'Products',evidence:'Synthetic prospect requested panels'},ctx,before);
 s=reduce(s,{type:'lead.schedule',id:leadId,at:due,consent:'Synthetic consent to an automated call',language:'English'},ctx,before);
 s=reduce(s,{type:'comms.policy',policy:{autoCalls:false,monthlyCeiling:200000,userDaily:5,tenantDaily:5}},ctx);
 s=reduce(s,{type:'comms.queue',leadId,kind:'Voice',estimate:1000},ctx);
 docs.set('/businesses/'+tenant,{value:s,stamp:'1'});
 const callId='22222222-2222-4222-8222-222222222222';
 const env={INTEGRATIONS_TENANT_ID:tenant,VOICE_ENABLED:'true',VAPI_ASSISTANT_REVIEWED:'true',VAPI_API_KEY:'fixture-key',VAPI_ASSISTANT_ID:'33333333-3333-4333-8333-333333333333',VAPI_PHONE_NUMBER_ID:'44444444-4444-4444-8444-444444444444',VAPI_WEBHOOK_SECRET:'fixture-webhook-secret',VOICE_ESTIMATE_INR_PER_MINUTE_MINOR:'1000'};
 const db=new FirebaseBridge(store).asDatabase();
 const transport=vi.fn(async()=>new Response(JSON.stringify({id:callId})));
 await Promise.allSettled([runJob(db,ctx,s.communicationJobs![0].id,env,firebaseMutate,transport),runJob(db,ctx,s.communicationJobs![0].id,env,firebaseMutate,transport)]);
 expect(transport).toHaveBeenCalledTimes(1);
 const raw=JSON.stringify({message:{type:'end-of-call-report',call:{id:callId,phoneNumberId:env.VAPI_PHONE_NUMBER_ID},durationSeconds:60,endedReason:'customer-ended-call',artifact:{transcript:'Please supply 2 pcs solar panels. Staff must confirm the exact model and delivery date.'}}});
 const request=(secret:string)=>new Request('https://worker.example/api/hooks/voice',{method:'POST',headers:{Authorization:'Bearer '+secret}});
 expect((await handleProviderWebhook(request('wrong'),raw,env,db,firebaseMutate)).status).toBe(401);
 expect((await handleProviderWebhook(request(env.VAPI_WEBHOOK_SECRET),raw,env,db,firebaseMutate)).status).toBe(200);
 await handleProviderWebhook(request(env.VAPI_WEBHOOK_SECRET),raw,env,db,firebaseMutate);
 s=docs.get('/businesses/'+tenant)!.value;
 expect(s.callRecords).toHaveLength(1);expect(s.leads[0].status).toBe('Details captured');expect(s.orders).toHaveLength(0);expect(s.quotes).toHaveLength(0);
 s=await firebaseMutate(db,sales,{type:'lead.promote',id:leadId,extraction:mockExtract(s.leads[0].requirements)});
 s=await firebaseMutate(db,sales,{type:'quote.create',enquiryId:s.leads![0].enquiryId,selections:[{productId:'p0',quantity:'2'}]});
 const quoteId=s.quotes[0].id;
 await expect(firebaseMutate(db,sales,{type:'quote.approve',id:quoteId,reason:'Cannot approve'})).rejects.toThrow(/admin/);
 await expect(firebaseMutate(db,sales,{type:'order.create',id:quoteId})).rejects.toThrow();
 s=await firebaseMutate(db,ctx,{type:'quote.approve',id:quoteId,reason:'Synthetic staff review completed'});
 s=await firebaseMutate(db,sales,{type:'quote.sent',id:quoteId});
 s=await firebaseMutate(db,sales,{type:'order.create',id:quoteId});
 expect(s.orders).toHaveLength(1);expect(s.invoices).toHaveLength(1);expect(s.invoices![0].status).toBe('Draft');
 await Promise.allSettled([firebaseMutate(db,sales,{type:'order.create',id:quoteId}),firebaseMutate(db,sales,{type:'order.create',id:quoteId})]);
 expect(docs.get('/businesses/'+tenant)!.value.orders).toHaveLength(1);
});
